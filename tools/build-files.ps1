<#
.SYNOPSIS
    Writes the build-time files build.bat needs, from the one version in
    version.txt.

.DESCRIPTION
    Two files are produced in the build directory:

      version_generated.h            the version for the resource block (file
                                     properties) and for the window title

      no-default-manifest.specs      the compiler's own "endfile" spec with the
                                     automatic default-manifest.o removed

    The second one needs a word of explanation.  On a native Windows MinGW-w64
    toolchain (WinLibs, MSYS2) the compiler appends a default-manifest.o to
    every link; a cross-compiler on Linux does not.  When the application
    carries its own manifest - wifiForce needs requireAdministrator - both end
    up in the executable, and the linker says:

        .rsrc merge failure: multiple non-default manifests

    Two RT_MANIFEST entries with the same id leave it to the loader to pick
    one, so the elevation request may be silently ignored.  This script rebuilds
    the endfile spec without that automatic object and build.bat passes
    -specs=... to g++, which leaves exactly one manifest in the binary.

.PARAMETER Version
    The version to write, as produced by tools\version.ps1.

.PARAMETER BuildDir
    Directory to write into; created if missing.

.PARAMETER Compiler
    The compiler whose specs are read.  Defaults to g++.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string] $Version,
    [Parameter(Mandatory = $true)] [string] $BuildDir,
    [string] $Compiler = 'g++'
)

$ErrorActionPreference = 'Stop'

if ($Version -notmatch '^(\d+)\.(\d+)(?:\.(\d+))?$') {
    Write-Error "'$Version' is not a version like 1.2"
    exit 1
}
$major = [int] $Matches[1]
$minor = [int] $Matches[2]
$patch = if ($Matches[3]) { [int] $Matches[3] } else { 0 }

if (-not (Test-Path -LiteralPath $BuildDir)) {
    New-Item -ItemType Directory -Path $BuildDir -Force | Out-Null
}

$header = @(
    '/* Generated by tools/build-files.ps1 from version.txt. Do not edit. */',
    '#ifndef WIFIFFORCE_VERSION_GENERATED_H',
    '#define WIFIFFORCE_VERSION_GENERATED_H',
    '',
    ('#define WIFIFFORCE_VERSION_DOTTED "{0}"' -f $Version),
    ('#define WIFIFFORCE_VERSION_COMMA  {0},{1},{2},0' -f $major, $minor, $patch),
    ('#define WIFIFFORCE_VERSION_BINARY "wifiForce_v{0}.exe"' -f $Version),
    '',
    '#endif'
) -join "`r`n"
[System.IO.File]::WriteAllText((Join-Path $BuildDir 'version_generated.h'), $header + "`r`n",
    (New-Object System.Text.UTF8Encoding($false)))

$specsPath = Join-Path $BuildDir 'no-default-manifest.specs'
if (Test-Path -LiteralPath $specsPath) { [System.IO.File]::Delete($specsPath) }

# The specs dump is plain text: "*endfile:" followed by its expansions, then a
# blank line and the next spec.
$dump = (& $Compiler -dumpspecs 2>$null) -join "`n"
$match = [regex]::Match($dump, '(?s)^\*endfile:[ \t]*\n(.*?)(?=\n\*|\z)', 'Multiline')
if (-not $match.Success) {
    Write-Host 'The compiler has no endfile spec; the manifest is left as it comes.'
} else {
    $endfile = $match.Groups[1].Value
    $stripped = $endfile -replace '%\{!shared:%:if-exists\(default-manifest\.o%s\)\}', ''
    if ($stripped -eq $endfile) {
        Write-Host 'The compiler does not insert a default manifest.'
    } else {
        [System.IO.File]::WriteAllText($specsPath, "*endfile:`n" + $stripped,
            (New-Object System.Text.UTF8Encoding($false)))
        Write-Host ('Default manifest suppressed: {0}' -f $specsPath)
    }
}

Write-Host ('Version files written for {0}: {1}' -f $Version, (Join-Path $BuildDir 'version_generated.h'))
